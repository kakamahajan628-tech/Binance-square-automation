"""Explicitly authorized empty-cluster start; never deletes/imports old data."""
import hashlib
import json
import os
from .models import utc
from .postgres import PostgresConnection, DatabaseUnavailable
from .database_transfer import line
from .database_failover import META_SCHEMA


CONFIRM = 'CONFIRM_EMPTY_NEW_CLUSTER'


def states_for(seed):
    proof = hashlib.sha256(json.dumps(seed,sort_keys=True).encode()).hexdigest()
    marker = {'required':True,'status':'verified','backup_sha256':proof,
              'verified_at':seed['cutoff'],'origin':'authorized_fresh_start',
              'history_preserved':False,'cluster_id':seed['cluster']}
    return {'schema_version':1,'emergency_stop':True,'worker_lease':{'owner':'','until':0},
            'database_migration':marker,
            'fresh_start':{'cluster_id':seed['cluster'],'cutoff':seed['cutoff'],
                           'old_history_imported':False,'old_queue_replayed':False}}


def baseline_for(states):
    hashed = hashlib.sha256()
    for key in sorted(states):
        if key in ('database_migration','worker_lease'):
            continue
        hashed.update(line({'type':'row','table':'state','values':[key,json.dumps(states[key],allow_nan=False)]}))
    return hashed.hexdigest()


def prepare_node(connection, cluster, baseline, states):
    from .store import SCHEMA
    with connection.transaction():
        schema = SCHEMA.replace('REAL','DOUBLE PRECISION').replace('id INTEGER PRIMARY KEY',
                       'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        for statement in schema.split(';'):
            if statement.strip():
                connection.execute(statement)
        connection.execute(META_SCHEMA)
        registered = connection.execute('SELECT * FROM square_replica_meta WHERE id=1').fetchone()
        if registered:
            if registered['cluster'] != cluster or registered['baseline'] != baseline:
                raise DatabaseUnavailable('Existing replica belongs to another history; fresh start refused')
            return
        for table in ('entities','audit','budgets'):
            if connection.execute('SELECT COUNT(*) AS n FROM '+table).fetchone()[0]:
                raise DatabaseUnavailable('Fresh start requires empty new databases; existing records are preserved')
        old = {row['key']:row['value'] for row in connection.execute('SELECT key,value FROM state')}
        # Only empty app bootstrap state may be replaced, never runtime/user history.
        if set(old) - set(states):
            raise DatabaseUnavailable('Existing runtime state is not an empty bootstrap; fresh start refused')
        if old.get('fresh_start') and json.loads(old['fresh_start']) != states['fresh_start']:
            raise DatabaseUnavailable('Another fresh-start checkpoint exists; refused')
        for key, value in states.items():
            connection.execute('INSERT INTO state VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',
                               (key,json.dumps(value,allow_nan=False)))
        connection.execute('INSERT INTO square_replica_meta VALUES (1,?,?,0,?)', (cluster,baseline,baseline))
        for table in ('entities','state','audit','budgets','square_replica_meta'):
            connection.execute('ALTER TABLE '+table+' ENABLE ROW LEVEL SECURITY')


def ensure(nodes, journal, *, factory=None):
    if os.getenv('DESK_DB_FRESH_START','') != CONFIRM:
        return
    factory = factory or (lambda url:PostgresConnection(url,connect_timeout=3))
    # Permanent seed makes partial setup/redeploy deterministic and non-destructive.
    journal.query('''CREATE TABLE IF NOT EXISTS square_fresh_seed
                    (id INTEGER PRIMARY KEY CHECK(id=1),cluster TEXT NOT NULL,cutoff INTEGER NOT NULL)''')
    journal.query('INSERT INTO square_fresh_seed VALUES (1,?,unixepoch()) ON CONFLICT DO NOTHING', (journal.cluster,))
    seeds = journal.query('SELECT cluster,cutoff FROM square_fresh_seed WHERE id=1')
    if (len(seeds) != 1 or seeds[0]['cluster'] != journal.cluster
            or type(seeds[0]['cutoff']) is not int or not 0 < seeds[0]['cutoff'] <= utc()+60):
        raise DatabaseUnavailable('Fresh-start seed differs; no reset performed')
    seed = seeds[0]
    states = states_for(seed)
    baseline = baseline_for(states)
    journal.fresh_states, journal.fresh_baseline = states, baseline
    from .turso_journal import SCHEMA as JOURNAL_SCHEMA
    for statement in JOURNAL_SCHEMA:
        journal.query(statement)
    heads = journal.query('SELECT * FROM square_cluster WHERE id=1')
    if heads:
        marker = json.loads(heads[0]['migration_marker'])
        if (heads[0]['cluster'] != journal.cluster or heads[0]['baseline'] != baseline
                or marker.get('origin') != 'authorized_fresh_start'):
            raise DatabaseUnavailable('Existing journal is not this fresh cluster; reset refused')
        # Normal redeploy: do not contact or rewrite every provider. Existing
        # registered replicas remain usable while a failed provider is offline.
        return
    ready = 0
    for name, url in nodes.items():
        connection = None
        try:
            connection = factory(url)
            prepare_node(connection,journal.cluster,baseline,states)
            ready += 1
        except DatabaseUnavailable:
            continue
        finally:
            if connection:
                connection.close()
    if ready < 2:
        raise DatabaseUnavailable('Fresh start needs at least two reachable empty PostgreSQL nodes')
    journal.initialize(baseline,states['database_migration'])

