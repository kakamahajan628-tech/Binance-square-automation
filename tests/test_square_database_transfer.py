class Cursor:
    def __init__(self, bridge):
        self.bridge = bridge
        self.raw = bridge.store.conn.cursor()
        self.itersize = None
    def __enter__(self):
        return self
    def __exit__(self, *args):
        self.raw.close()
    def execute(self, sql, args=None):
        self.raw.execute(sql.replace('public.', '').replace('%s', '?'), args or ())
    def executemany(self, sql, batch):
        self.bridge.batch_sizes.append(len(batch))
        self.raw.executemany(sql.replace('public.', '').replace('%s', '?'), batch)
    def __iter__(self):
        yield from self.raw


class Bridge:
    """SQLite exercises row/schema semantics; only PostgreSQL setup is stubbed."""
    def __init__(self, store):
        self.store, self.batch_sizes = store, []
    def cursor(self, name=None):
        return Cursor(self)
    @contextmanager
    def transaction(self):
        with self.store.transaction():
            yield
    def execute(self, sql, args=None):
        if sql.startswith(('SET TRANSACTION', 'SELECT pg_advisory', 'SELECT setval')):
            return None
        # SQLite schema was created by Store; PostgreSQL identity DDL is separately
        # validated by staged import tests and real psycopg query parsing.
        if 'GENERATED BY DEFAULT AS IDENTITY' in sql:
            sql = sql.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY')
        return self.store.conn.execute(sql.replace('public.', '').replace('%s', '?'), args or ())


def source_store():
    store = Store(':memory:')
    store.insert('draft', {'title': 'Confirmed publication', 'body': 'Observed research 5% text; $BTC?',
                           'receipt': {'id': 'remote-receipt'}, 'submitted_at': utc()}, 'published', id='published-id')
    store.insert('draft', {'title': 'Submission with missing receipt', 'body': 'Review remote account'}, 'sending', id='pending-id')
    store.insert('media', {'sha256': 'approved-image-hash', 'png_base64': 'exact-retained-bytes'}, 'stored', id='media-id')
    store.set('worker_lease', {'owner': 'old-worker', 'until': utc() + 120})
    store.set('paused', False)
    store.set('emergency_stop', False)
    store.set('runtime_settings', {'mode': 'automatic', 'hourly_cap': 3, 'gap_seconds': 1200})
    store.set('publisher_blocked', True)
    store.set('publisher_block_reason', {'code': 'account-restriction'})
    store.reserve_budget('2026-10-10', 'ai_tokens', 1234, 10000)
    store.log('CONTENT', 'Observed record')
    return store


def test_streaming_backup_restore_activation_preserves_history_controls_and_images(tmp_path):
    source = source_store()
    destination = Store(':memory:', migration_required=True)
    path = tmp_path / 'backup.jsonl.gz'
    try:
        manifest = write_backup(Bridge(source), path)
        assert manifest['real_publication_records'] == 2
        assert manifest['counts']['entities'] == 3
        assert manifest['source_controls'] == {'paused': False, 'emergency_stop': False, 'publisher_blocked': True}
        assert pending(destination.state(KEY))
        assert not destination.acquire_lease('new-worker')
        restored = restore_backup(Bridge(destination), path)
        assert restored['status'] == 'restored'
        assert not destination.acquire_lease('new-worker')
        assert destination.get('published-id')['payload'] == source.get('published-id')['payload']
        assert destination.get('pending-id')['status'] == 'uncertain'
        assert destination.get('media-id')['payload'] == source.get('media-id')['payload']
        assert destination.budget_used('2026-10-10', 'ai_tokens') == 1234
        assert destination.state('runtime_settings') == source.state('runtime_settings')
        assert destination.state('publisher_blocked') is True
        assert destination.state('publisher_block_reason') == source.state('publisher_block_reason')
        assert destination.state('worker_lease')['until'] == 0
        verified = activate_backup(Bridge(destination), path)
        assert verified['status'] == 'verified' and not pending(destination.state(KEY))
        assert destination.acquire_lease('new-worker')
        assert destination.state('emergency_stop') is True
        assert data_digest(Bridge(destination)) == manifest['data_sha256']
    finally:
        source.close()
        destination.close()


def test_restore_refuses_existing_application_rows_without_overwriting_them(tmp_path):
    source, target = source_store(), Store(':memory:')
    path = tmp_path / 'backup.gz'
    write_backup(Bridge(source), path)
    target.insert('draft', {'title': 'Keep this existing record'}, 'review', id='keep')
    before = target.list('draft')
    with pytest.raises(TransferError, match='contains application data'):
        restore_backup(Bridge(target), path)
    assert target.list('draft') == before
    assert not target.state(KEY)
    source.close()
    target.close()


def test_corrupt_or_partial_backup_does_not_modify_target(tmp_path):
    source, target = source_store(), Store(':memory:')
    path = tmp_path / 'backup.gz'
    write_backup(Bridge(source), path)
    data = gzip.decompress(path.read_bytes()).replace(b'Confirmed publication', b'Changed publication')
    path.write_bytes(gzip.compress(data))
    with pytest.raises(TransferError, match='checksum'):
        restore_backup(Bridge(target), path)
    assert not target.list('draft') and not target.state(KEY)
    source.close()
    target.close()


def test_target_changes_after_restore_prevent_activation(tmp_path):
    source, target = source_store(), Store(':memory:', migration_required=True)
    path = tmp_path / 'backup.gz'
    write_backup(Bridge(source), path)
    restore_backup(Bridge(target), path)
    target.set('runtime_settings', {'mode': 'approval'})
    with pytest.raises(TransferError, match='changed after restore'):
        activate_backup(Bridge(target), path)
    assert target.state(KEY)['status'] == 'restored'
    assert not target.acquire_lease('unsafe-worker')
    source.close()
    target.close()


def test_empty_development_backup_cannot_be_activated_as_production(tmp_path):
    source, target = Store(':memory:'), Store(':memory:')
    path = tmp_path / 'empty.gz'
    write_backup(Bridge(source), path)
    with pytest.raises(TransferError, match='history missing'):
        restore_backup(Bridge(target), path)
    assert not target.state(KEY)
    source.close()
    target.close()


def test_existing_output_is_not_overwritten_and_restore_batches_are_bounded(tmp_path):
    source, target = source_store(), Store(':memory:')
    for i in range(90):
        source.insert('draft', {'title': 'Historical note ' + str(i)}, 'expired', id='old-' + str(i))
    path = tmp_path / 'backup.gz'
    write_backup(Bridge(source), path)
    before = path.read_bytes()
    with pytest.raises(TransferError, match='already exists'):
        write_backup(Bridge(source), path)
    assert path.read_bytes() == before
    bridge = Bridge(target)
    restore_backup(bridge, path)
    assert max(bridge.batch_sizes) <= 32 and len(bridge.batch_sizes) >= 3
    source.close()
    target.close()


def test_migration_gate_is_independent_of_pause_unlock_and_policy_clear(tmp_path):
    store = Store(':memory:', migration_required=True)
    settings = Settings(database=':memory:', artifacts=str(tmp_path), paper_mode=False, live_enabled=True,
                        square_key='test-key', admin_token='test-password', policy_reviewed='2026-10-10')
    desk = Desk(settings, store=store)
    store.set('paused', False)
    store.set('emergency_stop', False)
    store.set('publisher_blocked', False)
    assert desk.publisher.policy.live_gate() == 'Database import not verified; publication held'
    status = desk.publisher.status()
    assert status['blocked'] is True and status['reason']['code'] == 'database_import_unverified'
    assert 'restore/activate' in status['next_step']
    app = create_app(settings, desk=desk, start_worker=False)
    with TestClient(app) as client:
        assert client.get('/health').status_code == 200
        assert client.head('/health').status_code == 200
        status = client.get('/health/details', auth=('desk', 'test-password')).json()
        assert status['publication']['database_migration']['status'] == 'needs_import'


def test_provider_detection_tls_preflight_and_cli_redaction(tmp_path, monkeypatch, capsys):
    assert is_aiven_url('postgres://user:secret@test.a.aivencloud.com:1234/defaultdb?sslmode=require')
    assert not is_aiven_url('postgres://user:secret@test.neon.tech/db?sslmode=require')
    monkeypatch.setenv('TEST_SOURCE_URL', 'postgres://user:private-password@test/db?sslmode=require')
    assert connection_url('TEST_SOURCE_URL').startswith('postgres://')
    monkeypatch.setenv('TEST_SOURCE_URL', 'postgres://user:private-password@test/db?sslmode=disable')
    assert main(['export', '--file', str(tmp_path/'no.gz'), '--env', 'TEST_SOURCE_URL']) == 1
    assert 'private-password' not in capsys.readouterr().out
    assert main(['restore', '--file', str(tmp_path/'no.gz'), '--env', 'TEST_SOURCE_URL']) == 1
    assert 'RESTORE_EMPTY_TARGET' in capsys.readouterr().out
